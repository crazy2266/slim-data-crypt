#include <stdio.h>
#include <string.h>
#include <sdcrypt/aes.h>
#include <sdcrypt/gcm.h>
#include <sdcrypt/errcode.h>
#include "test_common.h"

static void aes_enc_wrapper(const void *key, uint8_t out[16], const uint8_t in[16]) {
    sdc_aes_encrypt_block((const sdc_aes_key *)key, in, out);
}

/* NIST GCM Test Case 1: empty P, empty AAD, zero key/IV */
static void test_gcm_tc1(void) {
    uint8_t key[16] = {0}, iv[12] = {0};
    uint8_t tag[16];
    uint8_t exp[16] = {0x58,0xe2,0xfc,0xce,0xfa,0x7e,0x30,0x61,
                       0x36,0x7f,0x1d,0x57,0xa4,0xe7,0x45,0x5a};
    sdc_aes_key k;
    sdc_aes_set_encrypt_key(&k, key, 16);
    sdc_gcm_encrypt(aes_enc_wrapper, &k, iv, 12, NULL, 0, NULL, 0, NULL, tag);
    T_CHECK_MEM(tag, exp, 16, "GCM TC1 tag");
}

/* NIST GCM Test Case 2: 16-byte zero P, empty AAD */
static void test_gcm_tc2(void) {
    uint8_t key[16] = {0}, iv[12] = {0};
    uint8_t pt[16] = {0}, ct[16], tag[16];
    uint8_t exp_c[16] = {0x03,0x88,0xda,0xce,0x60,0xb6,0xa3,0x92,
                         0xf3,0x28,0xc2,0xb9,0x71,0xb2,0xfe,0x78};
    uint8_t exp_t[16] = {0xab,0x6e,0x47,0xd4,0x2c,0xec,0x13,0xbd,
                         0xf5,0x3a,0x67,0xb2,0x12,0x57,0xbd,0xdf};
    sdc_aes_key k;
    sdc_aes_set_encrypt_key(&k, key, 16);
    sdc_gcm_encrypt(aes_enc_wrapper, &k, iv, 12, NULL, 0, pt, 16, ct, tag);
    T_CHECK_MEM(ct, exp_c, 16, "GCM TC2 ciphertext");
    T_CHECK_MEM(tag, exp_t, 16, "GCM TC2 tag");

    /* decrypt + verify */
    uint8_t back[16];
    int rc = sdc_gcm_decrypt(aes_enc_wrapper, &k, iv, 12, NULL, 0, ct, 16, tag, back);
    T_CHECK(rc == SDC_ERR_OK && memcmp(back, pt, 16) == 0, "GCM TC2 decrypt+verify");

    /* tampered tag must fail */
    uint8_t bad[16]; memcpy(bad, tag, 16); bad[0] ^= 1;
    rc = sdc_gcm_decrypt(aes_enc_wrapper, &k, iv, 12, NULL, 0, ct, 16, bad, back);
    T_CHECK(rc != SDC_ERR_OK, "GCM TC2 tampered tag rejected");
}

/* NIST GCM Test Case 3: 64-byte P, 20-byte AAD */
static void test_gcm_tc3(void) {
    uint8_t key[16] = {0xfe,0xff,0xe9,0x92,0x86,0x65,0x73,0x1c,
                       0x6d,0x6a,0x8f,0x94,0x67,0x30,0x83,0x08};
    uint8_t iv[12] = {0xca,0xfe,0xba,0xbe,0xfa,0xce,0xdb,0xad,
                      0xde,0xca,0xf8,0x88};
    uint8_t aad[20] = {0xfe,0xed,0xfa,0xce,0xde,0xad,0xbe,0xef,
                       0xfe,0xed,0xfa,0xce,0xde,0xad,0xbe,0xef,
                       0xab,0xad,0xda,0xd2};
    /* NIST GCM Test Case 3: P is 60 bytes. */
    uint8_t pt[60] = {
        0xd9,0x31,0x32,0x25,0xf8,0x84,0x06,0xe5,0xa5,0x59,0x09,0xc5,0xaf,0xf5,0x26,0x9a,
        0x86,0xa7,0xa9,0x53,0x15,0x34,0xf7,0xda,0x2e,0x4c,0x30,0x3d,0x8a,0x31,0x8a,0x72,
        0x1c,0x3c,0x0c,0x95,0x95,0x68,0x09,0x53,0x2f,0xcf,0x0e,0x24,0x49,0xa6,0xb5,0x25,
        0xb1,0x6a,0xed,0xf5,0xaa,0x0d,0xe6,0x57,0xba,0x63,0x7b,0x39};
    uint8_t exp_c[60] = {
        0x42,0x83,0x1e,0xc2,0x21,0x77,0x74,0x24,0x4b,0x72,0x21,0xb7,0x84,0xd0,0xd4,0x9c,
        0xe3,0xaa,0x21,0x2f,0x2c,0x02,0xa4,0xe0,0x35,0xc1,0x7e,0x23,0x29,0xac,0xa1,0x2e,
        0x21,0xd5,0x14,0xb2,0x54,0x66,0x93,0x1c,0x7d,0x8f,0x6a,0x5a,0xac,0x84,0xaa,0x05,
        0x1b,0xa3,0x0b,0x39,0x6a,0x0a,0xac,0x97,0x3d,0x58,0xe0,0x91};
    uint8_t exp_t[16] = {0x5b,0xc9,0x4f,0xbc,0x32,0x21,0xa5,0xdb,
                         0x94,0xfa,0xe9,0x5a,0xe7,0x12,0x1a,0x47};
    uint8_t ct[60], tag[16], back[60];
    sdc_aes_key k;
    sdc_aes_set_encrypt_key(&k, key, 16);
    sdc_gcm_encrypt(aes_enc_wrapper, &k, iv, 12, aad, 20, pt, 60, ct, tag);
    T_CHECK_MEM(ct, exp_c, 60, "GCM TC3 ciphertext");
    T_CHECK_MEM(tag, exp_t, 16, "GCM TC3 tag");

    int rc = sdc_gcm_decrypt(aes_enc_wrapper, &k, iv, 12, aad, 20, ct, 60, tag, back);
    T_CHECK(rc == SDC_ERR_OK && memcmp(back, pt, 60) == 0, "GCM TC3 roundtrip");

    uint8_t zerotag[16] = {0};
    rc = sdc_gcm_decrypt(aes_enc_wrapper, &k, iv, 12, aad, 20, ct, 60, zerotag, back);
    T_CHECK(rc != SDC_ERR_OK, "GCM TC3 wrong tag rejected");
}

int main(void) {
    T_SUITE("AES-GCM");
    test_gcm_tc1();
    test_gcm_tc2();
    test_gcm_tc3();
    T_SUMMARY();
}
