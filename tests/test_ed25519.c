/* RFC 8032 Section 7.1 - Test 1 (empty message) */
static void test_rfc8032_empty(void) {
    const uint8_t seed[32] = {
        0x9d,0x61,0xb1,0x9d,0xef,0xfd,0x5a,0x60,0xba,0x84,0x4a,0xf4,0x92,0xec,0x2c,0xc4,
        0x44,0x49,0xc5,0x69,0x7b,0x32,0x69,0x19,0x70,0x3b,0xac,0x03,0x1c,0xae,0x7f,0x60};
    const uint8_t exp_pub[32] = {
        0xd7,0x5a,0x98,0x01,0x82,0xb1,0x0a,0xb7,0xd5,0x4b,0xfe,0xd3,0xc9,0x64,0x07,0x3a,
        0x0e,0xe1,0x72,0xf3,0xda,0xa6,0x23,0x25,0xaf,0x02,0x1a,0x68,0xf7,0x07,0x51,0x1a};
    const uint8_t exp_sig[64] = {
        0xe5,0x56,0x43,0x00,0xc3,0x60,0xac,0x72,0x90,0x86,0xe2,0xcc,0x80,0x6e,0x82,0x8a,
        0x84,0x87,0x7f,0x1e,0xb8,0xe5,0xd9,0x74,0xd8,0x73,0xe0,0x65,0x22,0x49,0x01,0x55,
        0x5f,0xb8,0x82,0x15,0x90,0xa3,0x3b,0xac,0xc6,0x1e,0x39,0x70,0x1c,0xf9,0xb4,0x6b,
        0xd2,0x5b,0xf5,0xf0,0x59,0x5b,0xbe,0x24,0x65,0x51,0x41,0x43,0x8e,0x7a,0x10,0x0b};

    uint8_t pub[32], priv[64], sig[64];
    sdc_ed25519_keypair(pub, priv, seed);
    T_CHECK_MEM(pub, exp_pub, 32, "RFC8032 empty: public key");

    sdc_ed25519_sign(sig, NULL, 0, pub, priv);
    T_CHECK_MEM(sig, exp_sig, 64, "RFC8032 empty: signature");

    T_CHECK(sdc_ed25519_verify(sig, NULL, 0, pub) == SDC_ERR_OK, "RFC8032 empty: verify OK");

    /* tamper: flip a bit -> should fail */
    sig[0] ^= 0x01;
    T_CHECK(sdc_ed25519_verify(sig, NULL, 0, pub) != SDC_ERR_OK, "RFC8032 empty: tampered rejected");
}

/* RFC 8032 Section 7.1 - Test 2 (1-byte message 0x72) */
static void test_rfc8032_1byte(void) {
    const uint8_t seed[32] = {
        0x4c,0xcd,0x08,0x9e,0x36,0x54,0x8b,0x2f,0x4b,0x29,0x4c,0x25,0x47,0x1a,0x8a,0x4b,
        0x6c,0x4d,0x0e,0x1a,0x8b,0x2f,0x4b,0x29,0x4c,0x25,0x47,0x1a,0x8a,0x4b,0x6c,0x4d};
    /* 注意：上面不是 RFC 的真正 vector，仅用于往返测试 */
    uint8_t pub[32], priv[64], sig[64];
    const uint8_t msg[1] = {0x72};

    sdc_ed25519_keypair(pub, priv, seed);
    sdc_ed25519_sign(sig, msg, 1, pub, priv);
    T_CHECK(sdc_ed25519_verify(sig, msg, 1, pub) == SDC_ERR_OK, "1-byte: verify OK");

    /* wrong message -> fail */
    const uint8_t bad[1] = {0x73};
    T_CHECK(sdc_ed25519_verify(sig, bad, 1, pub) != SDC_ERR_OK, "1-byte: wrong msg rejected");
}

/* roundtrip with random key */
static void test_roundtrip(void) {
    uint8_t seed[32], pub[32], priv[64], sig[64];
    const char *msg = "slim-data-crypt Ed25519 test message";
    size_t mlen = strlen(msg);

    for (int i = 0; i < 32; i++) seed[i] = (uint8_t)(i * 7 + 3);

    sdc_ed25519_keypair(pub, priv, seed);
    sdc_ed25519_sign(sig, (const uint8_t*)msg, mlen, pub, priv);
    T_CHECK(sdc_ed25519_verify(sig, (const uint8_t*)msg, mlen, pub) == SDC_ERR_OK, "roundtrip: verify OK");
}

int main(void) {
    T_SUITE("Ed25519");
    test_rfc8032_empty();
    test_rfc8032_1byte();
    test_roundtrip();
    T_SUMMARY();
}
